"""One passage recorded for several values: the index note vault/Meta/Repeated passages.md.
An Evidence note carries one value's reference, so a passage that sources several values stands in several Evidence notes (they are never merged: each holds its own
claim link and status). This index lists every such passage once, with links to its Evidence notes, so a reader who opens any of them sees the others through the
backlink. The file is generated from the notes (never authored) and checked by check_all.py.
usage: python passages.py [check|write]"""
import sys
import dmlib as D
import readable

INDEX = D.VAULT / "Meta" / "Repeated passages.md"
NL = chr(10)


def groups(nodes):
    """{(paper id, quote, locator, value in source): [Evidence names]} for the passages that stand in two or more Evidence notes of configuration values"""
    out = {}
    for (kind, name), p in nodes.items():
        if kind == "Evidence" and "record_file" not in p:
            key = (str(p.get("paper_id") or ""), str(p.get("quote") or ""), str(p.get("locator") or ""))
            if not (key[1] or key[2]):   # no passage and no place recorded: nothing to group by
                continue
            out.setdefault(key, []).append(name)
    return {k: sorted(v) for k, v in out.items() if len(v) > 1}


def text():
    nodes = D.read_all()
    sources = {n: p for (k, n), p in nodes.items() if k == "Source"}
    g = groups(nodes)
    lines = ["# Repeated passages", "",
             "Generated by tools/dm/passages.py from the Evidence notes; do not edit. %d passages stand in %d Evidence notes (one note per value they source)." % (len(g), sum(len(v) for v in g.values())), ""]
    for (paper, quote, locator), names in sorted(g.items(), key=lambda kv: (readable.cite(kv[0][0], sources), kv[0])):
        said = quote or locator
        lines.append("## %s - %s" % (readable.short(said, 160), readable.cite(paper, sources)))
        if locator and not locator.startswith(said[:60]) and not said.startswith(locator[:60]):
            lines.append("Where in the source: %s" % readable.short(locator, 200))
        for n in names:
            vis = str(nodes[("Evidence", n)].get("value_in_source") or "")
            lines.append("- [[%s]]%s" % (D.title("Evidence", n), (" (read from it: %s)" % readable.short(vis, 80)) if vis else ""))
        lines.append("")
    return NL.join(lines)


def problems():
    want = text()
    if not INDEX.exists() or INDEX.read_text(encoding="utf-8") != want:
        return ["vault/Meta/Repeated passages.md is not the index derived from the Evidence notes (run tools/dm/build_from_vault.py write)"]
    return []


def write():
    want = text()
    if not INDEX.exists() or INDEX.read_text(encoding="utf-8") != want:
        INDEX.write_text(want, encoding="utf-8", newline=NL)
        return True
    return False


def main():
    if (sys.argv[1] if len(sys.argv) > 1 else "check") == "write":
        print("repeated passages index", "written" if write() else "unchanged")
    bad = problems()
    for b in bad:
        print("PASSAGES", b)
    print("PASSAGES OK" if not bad else "PASSAGES FAILED")
    return 1 if bad else 0


if __name__ == "__main__":
    sys.exit(main())
