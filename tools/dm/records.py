    dict(code="basis", path=SA + "source_basis.csv", kind="csv", dg="Record"),
    dict(code="unsrc", path=SA + "unsourced_kind.csv", kind="csv", dg="Record", id_col="key"),
    dict(code="declared", path=SA + "declared_values.csv", kind="csv", dg="Record", id_col="key"),
