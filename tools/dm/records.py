"""Phase 3: the remaining authored files as vault notes, and back. Each file of SPECS is split into one note per row (CSV, JSONL) or per element (JSON), carries its
original order, and is regenerated by `generate`. DG-native types: audit items are Issue notes, methods and joins (sourcing_records.jsonl) are Claim notes with a Source link;
everything else is a Record note (a data row with no discourse meaning of its own: classifier rules, worklists, measurement tables, the growth web's parts, tool settings).
A note holds its row in the property `data` (JSON). Header notes ("REC - <code> header") hold the CSV columns. A JSONL line is written in one of four formats (property fmt)
so that every line regenerates byte-exact; a line that matches none is normalised to the default format and counted.
Seed with `python records.py seed`; `generate()` returns {path: text} for build_from_vault."""
