    dict(code="jepa", path="companion/TRUSOMA_JEPA_REFERENCES.csv", kind="csv", dg="Record", id_col="paper_id"),
    dict(code="gsrc", path=SA + "batch_2026-11-04_growth/sources.jsonl", kind="jsonl", dg="Record"),
    dict(code="wk8", path=SA + "batch_2026-11-04_wk8/sources.jsonl", kind="jsonl", dg="Record"),
